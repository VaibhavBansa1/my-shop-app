// Notifications + payment reminder walkthrough (web).
const { chromium } = require('playwright');
const path = require('path');
const BASE = process.env.BASE || 'http://localhost:3000';
const OUT = path.join(__dirname, '..', 'docs', 'screenshots');
async function pick(loc, text) { const v = await loc.evaluate((el, t) => [...el.options].find((o) => o.textContent.includes(t))?.value, text); await loc.selectOption(v); }
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await ctx.newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
  await page.goto(`${BASE}/signup`);
  await page.fill('input[autocomplete=name]', 'Owner');
  await page.fill('input[type=email]', `notify${Date.now()}@example.com`);
  await page.fill('input[type=password]', 'notify walk password');
  await page.click('button:has-text("Create account")');
  await page.waitForURL('**/orgs**');
  await page.click('text=+ Create a new business');
  await page.fill('form input >> nth=0', 'Bansal Store');
  await page.click('button:has-text("Create")');
  await page.waitForURL(/\/o\/[0-9a-f-]+$/);
  const base = page.url();
  await page.goto(`${base}/settings`);
  await page.fill('input[maxlength="130"]', 'bansalstore@okhdfcbank');
  await page.click('button:has-text("Save")');
  await page.waitForSelector('text=Business details saved');
  await page.goto(`${base}/items`);
  await page.click('text=+ New item');
  await page.fill('form input >> nth=0', 'Detergent 1kg');
  await page.fill('form input >> nth=4', '89');
  await page.fill('form input >> nth=6', '5');
  await page.fill('form input >> nth=7', '6');
  await page.fill('form input >> nth=8', '72');
  await page.waitForFunction(() => document.querySelector('form select').value !== '');
  await page.click('button:has-text("Save")');
  await page.waitForSelector('td:has-text("Detergent")');
  await page.goto(`${base}/ledgers`);
  await page.click('text=+ New ledger');
  await page.fill('form input >> nth=0', 'Ramesh Traders');
  await pick(page.locator('form select').first(), 'Sundry Debtors');
  await page.fill('form input >> nth=3', '98765 43210');
  await page.click('button:has-text("Save ledger")');
  await page.waitForSelector('text=Ramesh Traders');
  await page.goto(`${base}/vouchers/new?type=sales`);
  await page.waitForSelector('text=Items');
  await pick(page.locator('form select').first(), 'Ramesh');
  await pick(page.locator('.line select').first(), 'Detergent');
  await page.fill('.line input >> nth=0', '2');
  await page.click('button:has-text("Save")');
  await page.waitForSelector('text=Tax Invoice, text=Sales >> nth=0').catch(() => {});
  await page.waitForSelector('text=INV/');
  await page.goto(base);
  await page.waitForSelector('a:has-text("Notifications") .badge');
  console.log('unread badge:', await page.locator('a:has-text("Notifications") .badge').textContent());
  await page.click('a:has-text("Notifications")');
  await page.waitForSelector('text=Low stock: Detergent 1kg');
  await page.screenshot({ path: `${OUT}/notifications-desktop.png`, fullPage: true });
  await page.goto(`${base}/reports`);
  await page.click('button.chip:has-text("Receivables")');
  await page.click('a:has-text("Remind")');
  await page.waitForSelector('text=Payment reminder');
  const text = await page.locator('textarea').inputValue();
  console.log('reminder mentions UPI:', text.includes('bansalstore@okhdfcbank'), '| amount:', /₹178\.00/.test(text));
  await page.click('button.chip:has-text("हिन्दी")');
  await page.waitForFunction(() => document.querySelector('textarea').value.includes('बकाया'));
  const [popup] = await Promise.all([ctx.waitForEvent('page'), page.click('button:has-text("WhatsApp")')]);
  console.log('WhatsApp link:', popup.url().slice(0, 60));
  await popup.close();
  await page.waitForSelector('text=Reminder recorded');
  await page.reload();
  await page.waitForSelector('text=Last reminded');
  await page.screenshot({ path: `${OUT}/reminder-desktop.png`, fullPage: true });
  console.log('errors:', errors.length ? errors : 'none');
  await browser.close();
})().catch((e) => { console.error(e.message); process.exit(1); });
