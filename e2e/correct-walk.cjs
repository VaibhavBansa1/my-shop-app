const { chromium } = require('playwright');
async function pick(loc, text) { const v = await loc.evaluate((el, t) => [...el.options].find((o) => o.textContent.includes(t))?.value, text); await loc.selectOption(v); }
(async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
  await page.goto((process.env.BASE || 'http://localhost:3000') + '/signup');
  await page.fill('input[autocomplete=name]', 'Fixer');
  await page.fill('input[type=email]', `fix${Date.now()}@example.com`);
  await page.fill('input[type=password]', 'fixer test password');
  await page.click('button:has-text("Create account")');
  await page.waitForURL('**/orgs**');
  await page.click('text=+ Create a new business');
  await page.fill('form input >> nth=0', 'Fix Store');
  await page.click('button:has-text("Create")');
  await page.waitForURL(/\/o\/[0-9a-f-]+$/);
  const base = page.url();
  await page.goto(`${base}/items`);
  await page.click('text=+ New item');
  await page.fill('form input >> nth=0', 'Pen');
  await page.fill('form input >> nth=4', '10');
  await page.waitForFunction(() => document.querySelector('form select').value !== '');
  await page.click('button:has-text("Save")');
  await page.waitForSelector('td:has-text("Pen")');
  await page.goto(`${base}/vouchers/new?type=sales`);
  await page.waitForSelector('text=Items');
  await pick(page.locator('.line select').first(), 'Pen');
  await page.fill('.line input >> nth=0', '5');
  await page.click('button:has-text("Save")');
  await page.waitForSelector('text=INV/');
  await page.click('text=Correct…');
  await page.waitForSelector('text=You are correcting');
  await page.fill('.line input >> nth=0', '3');
  await page.click('button:has-text("Save")');
  await page.waitForSelector('text=INV/26-27/2');
  await page.goto(`${base}/vouchers`);
  await page.waitForSelector('text=INV/26-27/1');
  const rows = await page.locator('tbody tr').allTextContents();
  console.log(rows.join('\n'));
  console.log('errors:', errors.length ? errors : 'none');
  await browser.close();
})().catch((e) => { console.error(e.message); process.exit(1); });
