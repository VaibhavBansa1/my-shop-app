const { chromium } = require('playwright');
const OUT = require('path').join(__dirname, '..', 'docs', 'screenshots');
(async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
  await page.goto((process.env.BASE || 'http://localhost:3000') + '/signup');
  await page.fill('input[autocomplete=name]', 'Scan Tester');
  await page.fill('input[type=email]', `scan${Date.now()}@example.com`);
  await page.fill('input[type=password]', 'scan tester password');
  await page.click('button:has-text("Create account")');
  await page.waitForURL('**/orgs');
  await page.click('text=+ Create a new business');
  await page.fill('form input >> nth=0', 'Scan Store');
  await page.fill('form input >> nth=1', '23ABCDE1234F1Z8');
  await page.click('button:has-text("Create")');
  await page.waitForURL(/\/o\/[0-9a-f-]+$/);
  const base = page.url();
  await page.goto(`${base}/vouchers/new?type=purchase`);
  await page.waitForSelector('text=Scan a supplier invoice');
  await page.setInputFiles('input[type=file]', require('path').join(__dirname, '..', 'test', 'fixtures', 'invoice-sample.png'));
  await page.waitForSelector('text=Fill the purchase form', { timeout: 60000 });
  await page.click('text=+ Create supplier with this GSTIN');
  await page.waitForSelector('text=ANNAPURNA WHOLESALE TRADERS >> nth=0');
  await page.screenshot({ path: `${OUT}/scan-review-desktop.png`, fullPage: true });
  await page.click('text=Fill the purchase form');
  await page.waitForFunction(() => document.querySelectorAll('.line').length === 3, null, { timeout: 20000 });
  await page.screenshot({ path: `${OUT}/scan-filled-desktop.png`, fullPage: true });
  await page.click('button:has-text("Save")');
  await page.waitForSelector('text=PUR/', { timeout: 20000 });
  const total = await page.locator('.grand .num').textContent();
  const party = await page.locator('text=Party:').locator('..').textContent();
  console.log('party:', party);
  console.log('saved purchase total', total, 'errors:', errors.length ? errors : 'none');
  await browser.close();
})().catch((e) => { console.error(e.message); process.exit(1); });
